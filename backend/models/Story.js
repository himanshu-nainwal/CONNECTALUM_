import mongoose from "mongoose";

const storySchema = new mongoose.Schema(
  {
    title: { type: String, required: true },
    content: { type: String, required: true },
    author: { type: mongoose.Schema.Types.ObjectId, ref: "User", required: true },
    category: {
      type: String,
      enum: ["Career Journey", "Interview Experience", "Higher Studies", "Startup", "Campus Life"],
      default: "Career Journey",
    },
    company: { type: String, default: "" },
    ai_summary: {
      type: [String],
      default: [], // 3-bullet executive summary generated by AI
    },
    likes: { type: [mongoose.Schema.Types.ObjectId], ref: "User", default: [] },
    bookmarks: { type: [mongoose.Schema.Types.ObjectId], ref: "User", default: [] },
    is_verified: { type: Boolean, default: true },
    is_flagged: { type: Boolean, default: false },
    flag_reason: { type: String, default: "" },
    moderation_status: {
      type: String,
      enum: ["approved", "pending", "flagged"],
      default: "approved",
    },
  },
  { timestamps: true }
);

export default mongoose.model("Story", storySchema);
